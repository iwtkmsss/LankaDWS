// Resolve CLI entrypoints from each package's declared `bin` instead of a
// hard-coded internal path, so a Prisma/tsx layout change does not break setup.
function packageBin(packageName: string): string {
  const manifestPath = requireHere.resolve(`${packageName}/package.json`);
  const bin = (requireHere(manifestPath) as { bin?: string | Record<string, string> }).bin;
  const relative = typeof bin === 'string' ? bin : bin?.[packageName];
  if (!relative) throw new Error(`Cannot resolve bin for ${packageName}`);
  return resolve(dirname(manifestPath), relative);
}

